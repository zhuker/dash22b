package com.example.dash22b.obd

import org.junit.Assert.assertEquals
import org.junit.Test

class Mode09Test {

    private fun bytes(vararg v: Int) = ByteArray(v.size) { v[it].toByte() }

    /** VIN as the car sent it on 2026-08-30: five messages, four bytes each. */
    private val vinRaw = bytes(
        0xC2, 0x33, 0xF1, 0x09, 0x02, 0xF0,
        0x87, 0xF1, 0x10, 0x49, 0x02, 0x01, 0x00, 0x00, 0x00, 0x4A, 0x1E,
        0x87, 0xF1, 0x10, 0x49, 0x02, 0x02, 0x46, 0x31, 0x47, 0x44, 0xD7,
        0x87, 0xF1, 0x10, 0x49, 0x02, 0x03, 0x37, 0x30, 0x36, 0x35, 0xA8,
        0x87, 0xF1, 0x10, 0x49, 0x02, 0x04, 0x35, 0x4C, 0x35, 0x31, 0xBE,
        0x87, 0xF1, 0x10, 0x49, 0x02, 0x05, 0x30, 0x30, 0x34, 0x37, 0xA3
    )

    @Test
    fun `reassembles the ECU's VIN, which is the donor STI's`() {
        assertEquals("JF1GD70655L510047", Mode09.text(vinRaw, Mode09.PID_VIN))
    }

    @Test
    fun `messages are ordered by index, not by arrival`() {
        // Same VIN with the middle two messages swapped on the wire.
        val shuffled = bytes(
            0x87, 0xF1, 0x10, 0x49, 0x02, 0x03, 0x37, 0x30, 0x36, 0x35, 0xA8,
            0x87, 0xF1, 0x10, 0x49, 0x02, 0x01, 0x00, 0x00, 0x00, 0x4A, 0x1E,
            0x87, 0xF1, 0x10, 0x49, 0x02, 0x02, 0x46, 0x31, 0x47, 0x44, 0xD7,
            0x87, 0xF1, 0x10, 0x49, 0x02, 0x05, 0x30, 0x30, 0x34, 0x37, 0xA3,
            0x87, 0xF1, 0x10, 0x49, 0x02, 0x04, 0x35, 0x4C, 0x35, 0x31, 0xBE
        )

        assertEquals("JF1GD70655L510047", Mode09.text(shuffled, Mode09.PID_VIN))
    }

    @Test
    fun `splits the two calibration IDs the car reports`() {
        val raw = bytes(
            0x87, 0xF1, 0x10, 0x49, 0x04, 0x01, 0x41, 0x32, 0x5A, 0x4A, 0xED,
            0x87, 0xF1, 0x10, 0x49, 0x04, 0x02, 0x42, 0x31, 0x30, 0x4A, 0xC4,
            0x87, 0xF1, 0x10, 0x49, 0x04, 0x03, 0x00, 0x00, 0x00, 0x00, 0xD8,
            0x87, 0xF1, 0x10, 0x49, 0x04, 0x04, 0x00, 0x00, 0x00, 0x00, 0xD9,
            0x87, 0xF1, 0x10, 0x49, 0x04, 0x05, 0x41, 0x44, 0x33, 0x41, 0xD3,
            0x87, 0xF1, 0x10, 0x49, 0x04, 0x06, 0x31, 0x30, 0x31, 0x44, 0xB1,
            0x87, 0xF1, 0x10, 0x49, 0x04, 0x07, 0x00, 0x00, 0x00, 0x00, 0xDC,
            0x87, 0xF1, 0x10, 0x49, 0x04, 0x08, 0x00, 0x00, 0x00, 0x00, 0xDD
        )

        // Two 16-byte slots, not one run-on string: each pairs with one CVN.
        assertEquals(listOf("A2ZJB10J", "AD3A101D"), Mode09.calibrationIds(raw))
    }

    @Test
    fun `CVNs stay hex, one per calibration`() {
        val raw = bytes(
            0x87, 0xF1, 0x10, 0x49, 0x06, 0x01, 0x5C, 0x4D, 0x68, 0x47, 0x30,
            0x87, 0xF1, 0x10, 0x49, 0x06, 0x02, 0x2F, 0x5E, 0x61, 0x97, 0x5E
        )

        assertEquals(listOf("5C4D6847", "2F5E6197"), Mode09.calibrationVerificationNumbers(raw))
    }

    @Test
    fun `an empty capture yields nothing rather than throwing`() {
        assertEquals("", Mode09.text(ByteArray(0), Mode09.PID_VIN))
        assertEquals(emptyList<String>(), Mode09.calibrationIds(ByteArray(0)))
    }
}
